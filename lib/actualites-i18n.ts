export type Langue = "fr" | "en" | "de";

export const LANGUES: { code: Langue; nom: string; court: string }[] = [
  { code: "fr", nom: "Français", court: "FR" },
  { code: "en", nom: "English", court: "EN" },
  { code: "de", nom: "Deutsch", court: "DE" },
];

export function estLangue(valeur: unknown): valeur is Langue {
  return valeur === "fr" || valeur === "en" || valeur === "de";
}

export function langueDe(valeur: string | string[] | undefined): Langue {
  const v = Array.isArray(valeur) ? valeur[0] : valeur;
  return estLangue(v) ? v : "fr";
}

export const LOCALES: Record<Langue, string> = { fr: "fr-FR", en: "en-GB", de: "de-DE" };

// Remplace {nom} par sa valeur : « {n} commentaires ».
export function fmt(modele: string, valeurs: Record<string, string | number>): string {
  return modele.replace(/\{(\w+)\}/g, (_, cle: string) => String(valeurs[cle] ?? ""));
}

// Ajoute ?lang=… à une adresse quand la langue n'est pas le français.
export function avecLangue(chemin: string, langue: Langue): string {
  if (langue === "fr") return chemin;
  const [base, ancre] = chemin.split("#");
  return `${base}${base.includes("?") ? "&" : "?"}lang=${langue}${ancre ? `#${ancre}` : ""}`;
}

